def _time(i):
    return "05/Oct/2026:13:%02d:%02d +0500" % (10 + (i % 45), RNG.randint(0, 59))


def access(ip, url, status, ua=NORMAL_UA, reqtime=None):
    line = (
        '%s - - [%s] "GET %s HTTP/1.1" %d %d "-" "%s"'
        % (ip, _time(RNG.randint(0, 999)), url, status, RNG.randint(200, 9000), ua)
    )
    if reqtime is not None:
        line += " %.3f" % reqtime
    return line


def nginx_error(level, msg, ip=None):
    line = "2026/10/05 13:%02d:%02d [%s] 123#0: %s" % (
        RNG.randint(10, 59), RNG.randint(0, 59), level, msg
    )
    if ip:
        line += ", client: %s" % ip
    return line


def app(level, logger, msg):
    return "2026-10-05 13:%02d:%02d,%03d %s %s: %s" % (
        RNG.randint(10, 59), RNG.randint(0, 59), RNG.randint(0, 999),
        level, logger, msg,
    )


